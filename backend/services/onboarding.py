# Public API
# ---------------------------------------------------------------------------
def create_merchant(whatsapp_number: str, business_name: str, conn) -> MerchantContext:
    """Register a merchant from WhatsApp (merchant + store + WhatsApp source).

    If the number is already registered (for example two messages arrive at the same
    moment), returns the existing merchant instead of failing.
    """
    number = normalize_whatsapp_number(whatsapp_number)
    name = _clean_business_name(business_name)

    try:
        with _atomic(conn), conn.cursor() as cur:
            return _create_whatsapp_merchant_rows(cur, number, name)
    except WhatsAppNumberInUseError:
        existing = get_merchant_by_number(number, conn)
        if existing is not None:
            return existing
        raise


def create_whatsapp_merchant(whatsapp_number: str, business_name: str, conn, *, code_ttl_hours: int | None = None):
    """Flow B: register from WhatsApp and issue the CLAIM code to send back to the merchant."""
    number = normalize_whatsapp_number(whatsapp_number)
    name = _clean_business_name(business_name)

    with _atomic(conn), conn.cursor() as cur:
        context = _create_whatsapp_merchant_rows(cur, number, name)
        code = _create_code(
            cur, context.store_id, ConnectCodePurpose.CLAIM_MERCHANT, None,
            code_ttl_hours or CLAIM_CODE_TTL_HOURS,
        )

    return {
        "merchant_id": context.merchant_id,
        "store_id": context.store_id,
        "source_id": context.source_id,
        "connect_code": code.code,
        "expires_at": code.expires_at,
    }


def create_dashboard_merchant(user_id, business_name: str, conn, *, store_name: str | None = None, code_ttl_hours: int | None = None):
    """Flow A: a signed-in user creates a merchant and gets the LINK code to text on WhatsApp."""
    user = _as_uuid(user_id)
    name = _clean_business_name(business_name)
    store = _clean_business_name(store_name) if store_name else None

    with _atomic(conn), conn.cursor() as cur:
        merchant, store_id = _insert_merchant_and_store(cur, name, store)
        cur.execute(
            "INSERT INTO merchant_users (user_id, merchant_id, role) VALUES (%s, %s, 'owner')",
            (user, merchant.merchant_id),
        )
        code = _create_code(
            cur, store_id, ConnectCodePurpose.LINK_WHATSAPP, user,
            code_ttl_hours or LINK_CODE_TTL_HOURS,
        )

    return {
        "merchant_id": merchant.merchant_id,
        "store_id": store_id,
        "connect_code": code.code,
        "expires_at": code.expires_at,
    }


def create_connect_code(store_id, purpose: ConnectCodePurpose, *, conn, created_by_user_id=None, expires_in_hours: int | None = None) -> ConnectCode:
    """Issue a fresh code for a store, replacing any unused code of the same purpose."""
    purpose = ConnectCodePurpose(purpose)
    default_ttl = (
        LINK_CODE_TTL_HOURS if purpose == ConnectCodePurpose.LINK_WHATSAPP else CLAIM_CODE_TTL_HOURS
    )
    user = _as_uuid(created_by_user_id) if created_by_user_id is not None else None

    with _atomic(conn), conn.cursor() as cur:
        return _create_code(cur, _as_uuid(store_id), purpose, user, expires_in_hours or default_ttl)


def link_whatsapp_source_to_store(store_id, whatsapp_number: str, conn) -> UUID:
    number = normalize_whatsapp_number(whatsapp_number)
    with _atomic(conn), conn.cursor() as cur:
        return _link_whatsapp(cur, store_id, number)


def redeem_dashboard_connect_code(code: str, user_id, conn, *, expected_store_id=None) -> ConnectCode:
    """Flow B, dashboard side: a signed-in user claims a WhatsApp-created merchant.

    Consumes the code and makes the user the owner in one transaction. If the business
    already has an owner, nothing is consumed.
    """
    user = _as_uuid(user_id)

    with _atomic(conn), conn.cursor() as cur:
        consumed = _consume_code(
            cur, code, ConnectCodePurpose.CLAIM_MERCHANT,
            used_by_user_id=user, expected_store_id=expected_store_id,
        )
        cur.execute("SELECT merchant_id FROM stores WHERE store_id = %s", (consumed.store_id,))
        merchant_id = cur.fetchone()[0]
        try:
            cur.execute(
                "INSERT INTO merchant_users (user_id, merchant_id, role) VALUES (%s, %s, 'owner')",
                (user, merchant_id),
            )
        except psycopg.errors.UniqueViolation:
            raise ValueError("This business has already been claimed")

    return consumed


def redeem_whatsapp_connect_code(code: str, whatsapp_number: str, conn, *, expected_store_id=None) -> ConnectCode:
    """Flow A, WhatsApp side: link the sender's number to the dashboard merchant's store.

    If the number already belongs to another business, nothing is consumed.
    """
    number = normalize_whatsapp_number(whatsapp_number)

    with _atomic(conn), conn.cursor() as cur:
        consumed = _consume_code(
            cur, code, ConnectCodePurpose.LINK_WHATSAPP, expected_store_id=expected_store_id,
        )
        _link_whatsapp(cur, consumed.store_id, number)

    return consumed